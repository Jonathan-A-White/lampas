import { afterAll, describe, expect, it } from 'vitest';
import { db } from '../../src/data/db';

afterAll(() => db.close());

describe('the Dexie database', () => {
  it('opens at version 22 with the words, meta, settings, results, answers, talks, drills, readings, grammarKnown, grammarLevels, reviews, usage, tips and talkPictures, shares, requests, readingHistory, missTally, ladder and drillRuns stores', async () => {
    await db.open();
    expect(db.name).toBe('lampas');
    expect(db.verno).toBe(22);
    expect(db.tables.map((t) => t.name).sort()).toEqual(['answers', 'drillRuns', 'drills', 'grammarKnown', 'grammarLevels', 'ladder', 'meta', 'missTally', 'readingHistory', 'readings', 'requests', 'results', 'reviews', 'settings', 'shares', 'talkPictures', 'talks', 'tips', 'usage', 'words']);
    expect(db.words.schema.primKey.name).toBe('lemma');
    expect(db.words.schema.idxByName['lemmas']?.multi).toBe(true);
    expect(db.settings.schema.primKey.name).toBe('key');
    expect(db.results.schema.primKey.auto).toBe(true);
    expect(db.results.schema.idxByName['[lemma+when]']).toBeDefined();
    expect(db.answers.schema.primKey.auto).toBe(true);
    expect(db.answers.schema.idxByName['[ref+when]']).toBeDefined();
    expect(db.talks.schema.primKey.auto).toBe(true);
    expect(db.talks.schema.idxByName['[ref+when]']).toBeDefined();
    expect(db.drills.schema.primKey.auto).toBe(true);
    expect(db.drills.schema.idxByName['[lemma+step]']).toBeDefined();
    expect(db.readings.schema.primKey.name).toBe('ref');
    expect(db.grammarKnown.schema.primKey.name).toBe('term');
    expect(db.grammarLevels.schema.primKey.name).toBe('id');
    expect(db.grammarLevels.schema.idxByName['level']).toBeDefined();
    expect(db.reviews.schema.primKey.keyPath).toEqual(['kind', 'id']);
    expect(db.reviews.schema.idxByName['due']).toBeDefined();
    expect(db.reviews.schema.idxByName['kind']).toBeDefined();
    expect(db.ladder.schema.primKey.name).toBe('lang');
    expect(db.drillRuns.schema.primKey.auto).toBe(true);
    expect(db.drillRuns.schema.idxByName['ideaId']).toBeDefined();
    expect(db.drillRuns.schema.idxByName['at']).toBeDefined();
    expect(db.usage.schema.primKey.name).toBe('key');
    expect(db.usage.schema.idxByName['day']).toBeDefined();
    expect(db.usage.schema.idxByName['name']).toBeDefined();
    expect(db.tips.schema.primKey.name).toBe('id');
    expect(db.tips.schema.idxByName['status']).toBeDefined();
    expect(db.talkPictures.schema.primKey.auto).toBe(true);
    expect(db.talkPictures.schema.idxByName['turnId']).toBeDefined();
    expect(db.shares.schema.primKey.name).toBe('id');
    expect(db.shares.schema.idxByName['createdAt']).toBeDefined();
    expect(db.requests.schema.primKey.name).toBe('txid');
    expect(db.requests.schema.idxByName['sentAt']).toBeDefined();
    expect(db.requests.schema.idxByName['status']).toBeDefined();
    expect(db.readingHistory.schema.primKey.auto).toBe(true);
    expect(db.readingHistory.schema.idxByName['[lang+at]']).toBeDefined();
    expect(db.missTally.schema.primKey.keyPath).toEqual(['lang', 'unit']);
  });
});
