// scripts/numeral-sweep.ts — npm run numerals:sweep [-- --out <file>] [--lxx <folder>] (story mw-5r3p30.1127; src/data/numerals.ts, docs/numeral-sweep.md)
// Lists every numeral phrase of two or more words in the shipped Hebrew Old Testament, the Greek New Testament (public/data) and the Septuagint chapters that are shipped (dist/data-lxx, or public/data-lxx,
// or --lxx), adds each up as the Number sheet does, and checks the sum against the number the English chunks of its words say (englishNumber): a phrase whose English says another number is a MISMATCH,
// one whose English says none (a number spelled out of the parser's reach, a chunk with no number) is UNCHECKED. It writes docs/numeral-sweep.md: the counts, every mismatch, and the first of the unchecked.
// A second run on the same files writes the same bytes.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import type { Chapter } from '../src/data/chapter';
import { numeralPhrases, phraseEnglish, phraseSays, type NumeralLanguage } from '../src/data/numerals';

export const SWEEP_DOC = join('docs', 'numeral-sweep.md');
/** Where the shipped Septuagint chapters are looked for, in order (the first that holds a chapter). */
export const LXX_DIRS = [join('dist', 'data-lxx'), join('public', 'data-lxx')];
/** How many unchecked phrases the doc lists before saying how many more there are. */
const UNCHECKED_CAP = 60;

export type Status = 'match' | 'mismatch' | 'unchecked';
export interface PhraseFigure {
  /** 'gen 14:14' */
  ref: string;
  language: NumeralLanguage;
  /** the words of the phrase as written */
  words: string;
  sum: number;
  line: string;
  /** the English chunks the phrase's words are in */
  english: string[];
  /** the numbers those chunks say */
  numbers: number[];
  status: Status;
}

/** The figures of one chapter: each phrase, the English chunks its words belong to, and whether one of them says the sum. */
export function sweepChapter(code: string, chapter: Pick<Chapter, 'chapter' | 'verses'> & { lang?: string }): PhraseFigure[] {
  const language: NumeralLanguage = chapter.lang === 'hbo' ? 'hbo' : 'grc';
  const out: PhraseFigure[] = [];
  for (const verse of chapter.verses) {
    for (const phrase of numeralPhrases(verse.g, language)) {
      const english = phraseEnglish(verse, phrase);
      const numbers = phraseSays(verse, phrase);
      const status: Status = numbers.length === 0 ? 'unchecked' : numbers.includes(phrase.sum) ? 'match' : 'mismatch';
      out.push({ ref: `${code} ${chapter.chapter}:${verse.n}`, language, words: phrase.parts.map((p) => p.word.t).join(' '), sum: phrase.sum, line: phrase.line, english, numbers, status });
    }
  }
  return out;
}

const chapterFiles = (dir: string): { code: string; file: string }[] =>
  existsSync(dir)
    ? readdirSync(dir, { withFileTypes: true })
        .filter((d) => d.isDirectory())
        .flatMap((d) =>
          readdirSync(join(dir, d.name))
            .filter((f) => /^\d+\.json$/.test(f))
            .sort((a, b) => parseInt(a) - parseInt(b))
            .map((f) => ({ code: d.name, file: join(dir, d.name, f) })),
        )
        .sort((a, b) => (a.code === b.code ? 0 : a.code < b.code ? -1 : 1))
    : [];

/** The figures of every chapter of a data folder, and how many chapters it had. */
export function sweepDir(dir: string, language?: NumeralLanguage): { figures: PhraseFigure[]; chapters: number } {
  const files = chapterFiles(dir);
  const figures = files.flatMap(({ code, file }) => {
    const chapter = JSON.parse(readFileSync(file, 'utf8')) as Chapter;
    return sweepChapter(code, language && !chapter.lang ? { ...chapter, lang: language } : chapter);
  });
  return { figures, chapters: files.length };
}

export interface Sweep {
  /** one entry per data folder swept: its name, how many chapters it held and its figures */
  sources: { name: string; chapters: number; figures: PhraseFigure[] }[];
}

const cell = (text: string): string => text.replace(/\|/g, '\\|');

export function sweepMarkdown({ sources }: Sweep): string {
  const all = sources.flatMap((s) => s.figures);
  const count = (status: Status, list = all): number => list.filter((f) => f.status === status).length;
  const lines = [
    '# Numeral sweep',
    '',
    'GENERATED by `npm run numerals:sweep` (scripts/numeral-sweep.ts, story mw-5r3p30.1127): every numeral phrase of two or more words, added up as the Number sheet adds it (src/data/numerals.ts) and checked against the number the English chunks of its words say. Do not edit by hand.',
    '',
    'A **match** says the sum is a number one of its English chunks says. A **mismatch** says the English chunks say another number: the parser or the alignment is wrong, or the English reads the number another way. **Unchecked**: no English chunk of the phrase says a number the parser can read (a number spelled out of its reach, or a chunk with no number).',
    '',
    'The Septuagint row counts the chapters that `npm run lxx:ship -- --out dist/data-lxx` (or `--lxx <folder>`) has shipped on the host that ran the sweep: the repository itself ships none.',
    '',
    '| Text | Chapters | Phrases | Match | Mismatch | Unchecked |',
    '| --- | --- | --- | --- | --- | --- |',
    ...sources.map((s) => `| ${s.name} | ${s.chapters} | ${s.figures.length} | ${count('match', s.figures)} | ${count('mismatch', s.figures)} | ${count('unchecked', s.figures)} |`),
    '',
    `Total: ${all.length} phrases, ${count('match')} match, ${count('mismatch')} mismatch, ${count('unchecked')} unchecked.`,
    '',
    '## Mismatches',
    '',
    'What a mismatch is, in the text so far: **a noun splits the number** (Genesis 5, \'930 years\' is \'thirty years and nine hundred years\': each half is listed, and the Number sheet does not open for a sum the English does not say); **the English reads the number another way** (a variant or a choice of the translators: 1 Kings 4:26, 2 Chronicles 22:2, Ezekiel 40:49 and 45:1; a paraphrase, \'three or four miles\' for twenty-five stadia in John 6:19); **an idiom** (a hundred of you, a thousand of them: Leviticus 26:8, Deuteronomy 32:30, Judges 20:10, Isaiah 30:17). Where the English and the sum agree the word sheet is the Number sheet; where they do not, the word sheet opens as it always did.',
    '',
  ];
  const mismatches = all.filter((f) => f.status === 'mismatch');
  if (mismatches.length === 0) lines.push('None.', '');
  else {
    lines.push('| Verse | Words | Sum | English says | English chunks |', '| --- | --- | --- | --- | --- |');
    for (const f of mismatches) lines.push(`| ${f.ref} | ${cell(f.words)} | ${cell(f.line)} | ${f.numbers.join(', ')} | ${cell(f.english.join(' / '))} |`);
    lines.push('');
  }
  const unchecked = all.filter((f) => f.status === 'unchecked');
  lines.push('## Unchecked', '');
  if (unchecked.length === 0) lines.push('None.', '');
  else {
    lines.push('| Verse | Words | Sum | English chunks |', '| --- | --- | --- | --- |');
    for (const f of unchecked.slice(0, UNCHECKED_CAP)) lines.push(`| ${f.ref} | ${cell(f.words)} | ${cell(f.line)} | ${cell(f.english.join(' / '))} |`);
    if (unchecked.length > UNCHECKED_CAP) lines.push('', `${unchecked.length - UNCHECKED_CAP} more not listed.`);
    lines.push('');
  }
  return lines.join('\n');
}

export function runSweep(argv: readonly string[], log: (line: string) => void = () => {}): { sweep: Sweep; out: string; changed: boolean } {
  const flag = (name: string): string | undefined => argv[argv.indexOf(name) + 1];
  const out = argv.includes('--out') ? (flag('--out') as string) : SWEEP_DOC;
  const lxxDirs = argv.includes('--lxx') ? [flag('--lxx') as string] : LXX_DIRS;
  const data = sweepDir(join('public', 'data'));
  const hebrew = data.figures.filter((f) => f.language === 'hbo');
  const greek = data.figures.filter((f) => f.language === 'grc');
  const hebrewChapters = chapterFiles(join('public', 'data')).filter(({ file }) => (JSON.parse(readFileSync(file, 'utf8')) as Chapter).lang === 'hbo').length;
  const sources: Sweep['sources'] = [
    { name: 'Hebrew Old Testament', chapters: hebrewChapters, figures: hebrew },
    { name: 'Greek New Testament', chapters: data.chapters - hebrewChapters, figures: greek },
  ];
  const lxxDir = lxxDirs.find((dir) => chapterFiles(dir).length > 0);
  if (lxxDir) {
    const lxx = sweepDir(lxxDir, 'grc');
    sources.push({ name: 'Septuagint', chapters: lxx.chapters, figures: lxx.figures });
  } else sources.push({ name: 'Septuagint (no shipped chapter found)', chapters: 0, figures: [] });
  const sweep = { sources };
  const text = sweepMarkdown(sweep);
  const before = existsSync(out) ? readFileSync(out, 'utf8') : undefined;
  if (before !== text) writeFileSync(out, text);
  log(`${sources.map((s) => `${s.name}: ${s.chapters} chapters, ${s.figures.length} phrases`).join('; ')}: ${before === text ? 'unchanged' : 'wrote'} ${out}`);
  return { sweep, out, changed: before !== text };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  try {
    runSweep(process.argv.slice(2), console.log);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exit(1);
  }
}
