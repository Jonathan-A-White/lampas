// scripts/seed-build.ts — builds src/data/seed-words.ts from docs/example-words.md and src/data/seed-words-hbo.ts from the Hebrew frequency table and lexicon (`npm run seed:build`).
// Parses the table's columns (#, Greek lemma, Lvl, Lsn, English gloss, Part of speech, note) and keeps one
// entry per distinct lemma: the lemma as BMA shows it, the gloss, the lowest Lsn of its rows, the part of speech.
// Runs under plain node (type stripping), so it only uses erasable TypeScript.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { cleanGloss } from '../src/data/gloss.ts';
import { withAoristNote } from '../src/data/irregular-aorists.ts';
import type { SeedWord } from '../src/data/seedWord.ts';

/** The distinct lemmas of the md's table, in the order they first appear. */
export function parseExampleWords(md: string): SeedWord[] {
  const byLemma = new Map<string, SeedWord>();
  for (const line of md.split('\n')) {
    if (!line.startsWith('|')) continue;
    const cells = line.split('|').slice(1, -1).map((c) => c.trim());
    if (cells.length < 6 || !/^\d+$/.test(cells[0])) continue; // the header, the rule and prose
    const [, rawLemma, , lsn, gloss, pos] = cells;
    const lemma = rawLemma.normalize('NFC');
    const lesson = Number(lsn);
    const seen = byLemma.get(lemma);
    if (!seen) byLemma.set(lemma, { lemma, gloss: withAoristNote(lemma, cleanGloss(gloss)), lesson, pos }); // 'dat: in, by, with' is 'in, by, with (dative)'; a listed verb ends '(aorist X)'
    else if (lesson < seen.lesson) seen.lesson = lesson;
  }
  return [...byLemma.values()];
}

const str = (s: string) => JSON.stringify(s);

/** How many Hebrew lemmas the Hebrew seed holds: the commonest of the Old Testament. PROVISIONAL: the article and אֵת are in, since the frontier's frequency rule (src/data/frontier.ts) decides what is taught. */
export const HEBREW_SEED_SIZE = 100;

/** The shape of a row of public/data/frequency-hbo.json and an entry of lexicon-hbo.json that the seed reads. */
interface HebrewFrequency {
  lemma: string;
}
type HebrewLexicon = Record<string, { g: string; c: string }>;

/**
 * The commonest HEBREW_SEED_SIZE Hebrew lemmas, commonest first (frequency-hbo.json is by Strong's number, so a headword two numbers share is counted at its first), each with the
 * TBESH gloss and part of speech lexicon-hbo.json gives it, lesson 0 (no BMA lesson) and lang 'hbo'. A lemma the lexicon lacks is an error: the seed would carry no gloss.
 */
export function hebrewSeed(frequency: HebrewFrequency[], lexicon: HebrewLexicon): SeedWord[] {
  const words = new Map<string, SeedWord>();
  for (const { lemma: raw } of frequency) {
    if (words.size === HEBREW_SEED_SIZE) break;
    const lemma = raw.normalize('NFC');
    if (words.has(lemma)) continue;
    const entry = Object.hasOwn(lexicon, lemma) ? lexicon[lemma] : undefined;
    if (!entry) throw new Error(`The Hebrew lexicon has no entry for ${lemma}`);
    words.set(lemma, { lemma, lang: 'hbo', gloss: entry.g, lesson: 0, pos: entry.c });
  }
  return [...words.values()];
}

/** The text of src/data/seed-words-hbo.ts for these words. */
export function renderHebrewSeed(words: SeedWord[]): string {
  const rows = words
    .map((w) => `  { lemma: ${str(w.lemma)}, lang: 'hbo', gloss: ${str(w.gloss)}, lesson: ${w.lesson}, pos: ${str(w.pos)} },`)
    .join('\n');
  return `// The ${words.length} commonest Hebrew lemmas of the Old Testament with their TBESH glosses, lesson 0 (a starting list for the Hebrew words he learns).
// Generated by scripts/seed-build.ts from public/data/frequency-hbo.json and lexicon-hbo.json (npm run seed:build); do not edit by hand.
import type { SeedWord } from './seedWord';

export const SEED_WORDS_HBO: SeedWord[] = [
${rows}
];
`;
}

/** The text of src/data/seed-words.ts for these words. */
export function renderSeed(words: SeedWord[]): string {
  const rows = words
    .map((w) => `  { lemma: ${str(w.lemma)}, gloss: ${str(w.gloss)}, lesson: ${w.lesson}, pos: ${str(w.pos)} },`)
    .join('\n');
  return `// An example word list (the owner's own BMA words, lessons 1-10); replace or extend it with Import.
// Generated by scripts/seed-build.ts from docs/example-words.md (npm run seed:build); do not edit by hand.
import type { SeedWord } from './seedWord';

export const SEED_WORDS: SeedWord[] = [
${rows}
];
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const md = readFileSync(new URL('../docs/example-words.md', import.meta.url), 'utf8');
  const words = parseExampleWords(md);
  writeFileSync(new URL('../src/data/seed-words.ts', import.meta.url), renderSeed(words));
  console.log(`src/data/seed-words.ts: ${words.length} words from docs/example-words.md`);
  const frequency = JSON.parse(readFileSync(new URL('../public/data/frequency-hbo.json', import.meta.url), 'utf8')) as HebrewFrequency[];
  const lexicon = JSON.parse(readFileSync(new URL('../public/data/lexicon-hbo.json', import.meta.url), 'utf8')) as HebrewLexicon;
  const hebrew = hebrewSeed(frequency, lexicon);
  writeFileSync(new URL('../src/data/seed-words-hbo.ts', import.meta.url), renderHebrewSeed(hebrew));
  console.log(`src/data/seed-words-hbo.ts: ${hebrew.length} words from public/data/frequency-hbo.json and lexicon-hbo.json`);
}
