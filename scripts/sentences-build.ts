// scripts/sentences-build.ts — npm run sentences:build (mw-5r3p30.897): where a sentence of the Greek New Testament ends. The app's Greek has no punctuation (the MSB table keeps only the Greek
// question mark and the elision apostrophe, docs/greek-edition.md), so the ends are read from Robinson-Pierpont 2018, which is punctuated (github.com/byztxt/byzantine-majority-text, tag v3.3.2,
// the files scripts/greek-edition.ts fetches into data/raw/rp2018): a word followed by a full stop, a Greek question mark (;) or an exclamation mark ends a sentence; the ano teleia (·), the comma and
// the colon do not (a sentence ends there only if the diagram grind says so, which this build cannot ask). Each RP word is paired with the app's own word of the verse (public/data/<book>/<n>.json)
// by greek-edition's alignment, and the table written is src/diagram/sentenceEnds.ts: for a chapter, 'verse:word' places, the word an index into the verse's `g`. Needs the network the first time.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import type { Chapter } from '../src/data/chapter';
import { align, loadEdition, rpWords, RP_SOURCES, type RpWord } from './greek-edition';

const OUT = 'src/diagram/sentenceEnds.ts';
/** the marks that end a sentence in RP: a full stop, the Greek question mark (NFC makes it ;), an exclamation mark */
const ENDING = /[.;!?]/u;

/** One word of the app's verse as an RpWord (the elision apostrophe is the word's own); a word that is all marks counts as an empty word. */
const tableWord = (text: string): RpWord => rpWords(text)[0] ?? { word: text, marks: '' };

/** The places of one chapter where a sentence ends: 'verse:word' */
export function endsOfChapter(chapter: Chapter, rp: Map<string, string>): string[] {
  const out: string[] = [];
  for (const verse of chapter.verses) {
    const rpText = rp.get(`${chapter.chapter}:${verse.n}`);
    if (rpText === undefined || verse.g.length === 0) continue;
    const table = verse.g.map((w) => tableWord(w.t));
    const theirs = rpWords(rpText);
    const pairs = align(table, theirs);
    let lastTable = -1;
    for (const { a, b } of pairs) {
      if (a !== null) lastTable = a;
      if (b !== null && ENDING.test(theirs[b].marks) && lastTable >= 0) {
        const place = `${verse.n}:${lastTable}`;
        if (out[out.length - 1] !== place) out.push(place);
      }
    }
  }
  return out;
}

export async function run(options: { rawDir: string; log: (line: string) => void }): Promise<void> {
  const rp = await loadEdition('2018', options.rawDir);
  const lines: string[] = [];
  let ends = 0;
  for (const code of Object.keys(RP_SOURCES['2018'].files)) {
    const dir = `public/data/${code}`;
    const verses = rp.get(code);
    if (!verses) throw new Error(`no RP2018 text for ${code}`);
    const chapters = readdirSync(dir).filter((f) => /^\d+\.json$/.test(f)).sort((a, b) => parseInt(a, 10) - parseInt(b, 10));
    const parts: string[] = [];
    for (const file of chapters) {
      const chapter = JSON.parse(readFileSync(`${dir}/${file}`, 'utf8')) as Chapter;
      const list = endsOfChapter(chapter, verses);
      ends += list.length;
      parts.push(`    ${chapter.chapter}: '${list.join(' ')}',`);
    }
    lines.push(`  ${/^\d/.test(code) ? `'${code}'` : code}: {\n${parts.join('\n')}\n  },`);
  }
  const file =
    `// src/diagram/sentenceEnds.ts — GENERATED by npm run sentences:build (scripts/sentences-build.ts, mw-5r3p30.897); do not edit by hand.\n` +
    `// Where a sentence of the Greek New Testament ends, by book code and chapter: 'verse:word' places (the word is an index into the verse's \`g\`), read from Robinson-Pierpont 2018's punctuation\n` +
    `// (a full stop, a Greek question mark or an exclamation mark ends a sentence; the ano teleia, the comma and the colon do not). ${ends} places.\n` +
    `export const SENTENCE_ENDS: Record<string, Record<number, string>> = {\n${lines.join('\n')}\n};\n`;
  writeFileSync(OUT, file);
  options.log(`${ends} sentence ends in ${lines.length} books, written to ${OUT}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  run({ rawDir: 'data/raw', log: console.log }).catch((error: unknown) => {
    console.error(error);
    process.exit(1);
  });
}
